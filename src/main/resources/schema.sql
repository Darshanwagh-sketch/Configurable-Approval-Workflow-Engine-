-- Schema definition for Configurable Approval Workflow Engine (H2 / Standard ANSI SQL)

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS approval_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_type VARCHAR(50) NOT NULL,
    step_order INT NOT NULL,
    role VARCHAR(30) NOT NULL,
    workflow_version INT NOT NULL DEFAULT 1,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_step_workflow_order UNIQUE (request_type, workflow_version, step_order)
);

CREATE TABLE IF NOT EXISTS requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_by VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    current_step_order INT,
    workflow_version INT NOT NULL DEFAULT 1,
    payload CLOB,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS approval_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    action VARCHAR(35) NOT NULL,
    action_by VARCHAR(50) NOT NULL,
    action_at TIMESTAMP NOT NULL,
    step_order INT,
    remarks VARCHAR(1000)
);

CREATE INDEX IF NOT EXISTS idx_requests_created_by ON requests(created_by);
CREATE INDEX IF NOT EXISTS idx_requests_status ON requests(status);
CREATE INDEX IF NOT EXISTS idx_history_request_id ON approval_history(request_id);
